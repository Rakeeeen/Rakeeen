"""Writes the sketch-icon data files in src/ui/ from shapes.py. Run: python3 scripts/illustrations/build.py"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import draw

# At icon size a canvas unit is a few hundredths of a pixel, so a few units of simplification can't be seen.
draw.EPS = 4
from shapes import ICONS, BOIL_SEEDS, FILES

def layers(pen):
    return [[paper, ink] for paper, ink in getattr(pen, 'done', []) + [(pen.paper, pen.ink)]]

data = {
    name: {'frames': [layers(spec['still'](seed)) for seed in BOIL_SEEDS]}
    for name, spec in ICONS.items()
}
assert sorted(sum(FILES.values(), [])) == sorted(data), 'every icon must be in exactly one file'

UI = os.path.join(HERE, '..', '..', 'src', 'ui')
for filename, names in FILES.items():
    out = os.path.join(UI, filename)
    with open(out, 'w') as f:
        f.write('// Generated by scripts/illustrations/build.py. Edit the drawings there, not here.\n\n')
        if filename == 'sketchIcons.data.ts':
            f.write("/** Each layer is [paper shapes, ink shapes]; each frame is one redraw for the line boil. */\n")
            f.write('export type Layers = ReadonlyArray<readonly [readonly string[], readonly string[]]>;\n')
            f.write('export interface SketchIcon { frames: readonly Layers[] }\n\n')
        else:
            f.write("import type { SketchIcon } from '@/ui/sketchIcons.data';\n\n")
        for name in names:
            f.write(f'export const {name.upper()}_ICON: SketchIcon = {json.dumps(data[name], separators=(",", ":"))};\n')
    print('wrote', os.path.relpath(out), os.path.getsize(out) // 1024, 'KB')
